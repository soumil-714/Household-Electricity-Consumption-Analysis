# Convert appliance usage hours into kWh
def convert_to_kwh(hours, wattage):
    return (hours * wattage) / 1000


# Function to get valid float input
def get_valid_float_input(prompt):
    while True:
        try:
            value = float(input(prompt).strip())

            if value < 0:
                print("Value cannot be negative. Please enter a positive value.")
                continue

            return value

        except ValueError:
            print("Invalid input! Please enter a numeric value.")


# User Input Electricity Usage Analysis and Bill Prediction
def user_input_usage_analysis():

    # Preloaded appliances with wattage
    preloaded_appliances = {
        "Fan": 62.5,
        "Fridge": 150,
        "AC": 1500,
        "Monitor": 22.5,
        "TV": 125
    }

    selected_appliances = {}

    # City selection
    cities = df['City'].unique()

    print("\nAvailable Cities:")
    for i, city in enumerate(cities, 1):
        print(f"{i}. {city}")

    print(f"{len(cities) + 1}. Enter a custom tariff rate")

    while True:
        try:
            choice = int(input("Select an option: "))

            if choice == len(cities) + 1:
                tariff_rate = get_valid_float_input("Enter your custom tariff rate (₹ per kWh): ")
                selected_city = "Custom Tariff"
                break

            elif 1 <= choice <= len(cities):
                selected_city = cities[choice - 1]
                tariff_rate = df[df['City'] == selected_city]['TariffRate'].mean()
                print(f"Selected City: {selected_city}, Tariff Rate: ₹{tariff_rate:.2f} per kWh")
                break

            else:
                print("Invalid choice! Please select a valid city option.")

        except ValueError:
            print("Invalid input! Please enter a number.")

    # Ask user which preloaded appliances they use
    print("\nSelect Appliances You Use:")

    for appliance, wattage in preloaded_appliances.items():
        use_appliance = input(f"Do you use {appliance}? (yes/no): ").strip().lower()

        if use_appliance == "yes":
            selected_appliances[appliance] = wattage
        else:
            print(f"{appliance} removed from calculation.")

    # Add custom appliances
    add_custom = input("\nDo you want to add any custom appliance? (yes/no): ").strip().lower()

    if add_custom == "yes":
        while True:
            appliance_name = input("Enter custom appliance name: ").strip().title()
            wattage = get_valid_float_input(f"Enter wattage for {appliance_name}: ")

            selected_appliances[appliance_name] = wattage
            print(f"{appliance_name} added with {wattage} W.")

            more = input("Do you want to add another custom appliance? (yes/no): ").strip().lower()

            if more != "yes":
                break

    # If no appliance selected
    if len(selected_appliances) == 0:
        print("No appliances selected. Cannot calculate electricity usage.")
        return

    print("\nFinal Selected Appliances:")
    for appliance, wattage in selected_appliances.items():
        print(f"- {appliance} ({wattage} W)")

    print("\nEnter 7-day usage hours in one line.")
    print("Example: 5 6 5 7 6 5 4")

    appliance_usage = {}

    # Take 7-day input in one line for each selected appliance
    for appliance in selected_appliances:
        while True:
            try:
                usage_input = input(f"Enter {appliance} usage for 7 days: ").strip().split()

                if len(usage_input) != 7:
                    print("Please enter exactly 7 values.")
                    continue

                usage_values = [float(value) for value in usage_input]

                if any(value < 0 for value in usage_values):
                    print("Usage hours cannot be negative.")
                    continue

                appliance_usage[appliance] = usage_values
                break

            except ValueError:
                print("Invalid input! Please enter numeric values only.")

    # Calculate daily kWh
    daily_kwh = []

    for day in range(7):
        total_kwh = 0

        for appliance, wattage in selected_appliances.items():
            hours = appliance_usage[appliance][day]
            total_kwh += convert_to_kwh(hours, wattage)

        daily_kwh.append(total_kwh)

    avg_daily_kwh = sum(daily_kwh) / 7
    monthly_kwh = avg_daily_kwh * 30
    estimated_bill = monthly_kwh * tariff_rate

    # Display daily usage table
    print("\n🔹 Electricity Usage Trends (kWh per day):")

    print(tabulate(
        [[f"Day {i + 1}", round(daily_kwh[i], 2)] for i in range(7)],
        headers=['Day', 'kWh Used'],
        tablefmt='grid'
    ))

    print(f"\nSelected City / Tariff Type: {selected_city}")
    print(f"Average Daily Consumption: {avg_daily_kwh:.2f} kWh")
    print(f"Estimated Monthly Consumption: {monthly_kwh:.2f} kWh")
    print(f"Estimated Monthly Electricity Bill: ₹{estimated_bill:.2f}")

    # Visualization
    plt.figure(figsize=(8, 5))
    plt.plot(range(1, 8), daily_kwh, marker='o', linestyle='-')
    plt.title('Electricity Usage Trends for 7 Days')
    plt.xlabel('Day')
    plt.ylabel('Electricity Consumption (kWh)')
    plt.xticks(range(1, 8))
    plt.grid()
    plt.show()


