# Improved Automated Electricity Bill Prediction City-wise from Dataset

def automated_electricity_bill_prediction():
    # Required numeric columns
    appliance_cols = [
        'Fan_hours',
        'Refrigerator_hours',
        'AirConditioner_hours',
        'Monitor_hours',
        'Television_hours'
    ]

    required_cols = appliance_cols + ['TariffRate', 'City']

    # Check if all required columns exist
    missing_cols = [col for col in required_cols if col not in df.columns]

    if missing_cols:
        print(f"Error: Missing columns in dataset - {missing_cols}")
        return

    # Convert numeric columns safely
    numeric_cols = appliance_cols + ['TariffRate']

    df[numeric_cols] = df[numeric_cols].apply(pd.to_numeric, errors='coerce')

    # Fill missing numeric values with median
    df[numeric_cols] = df[numeric_cols].fillna(df[numeric_cols].median())

    # Calculate city-wise average appliance usage
    city_avg_usage = df.groupby('City')[appliance_cols].mean()

    # Calculate city-wise average tariff rate
    city_avg_tariff = df.groupby('City')['TariffRate'].mean()

    # Convert average daily appliance usage to monthly kWh city-wise
    city_monthly_kwh = (
        (city_avg_usage['Fan_hours'] * 30 * 0.0625) +
        (city_avg_usage['Refrigerator_hours'] * 30 * 0.150) +
        (city_avg_usage['AirConditioner_hours'] * 30 * 1.5) +
        (city_avg_usage['Monitor_hours'] * 30 * 0.0225) +
        (city_avg_usage['Television_hours'] * 30 * 0.125)
    )

    # Calculate predicted monthly bill city-wise
    predicted_bills = city_monthly_kwh * city_avg_tariff

    # Create final result table
    result = pd.DataFrame({
        'City': predicted_bills.index,
        'Average Monthly Units (kWh)': city_monthly_kwh.values,
        'Average Tariff Rate (₹/kWh)': city_avg_tariff.values,
        'Estimated Monthly Bill (₹)': predicted_bills.values
    })

    # Round values for better display
    result['Average Monthly Units (kWh)'] = result['Average Monthly Units (kWh)'].round(2)
    result['Average Tariff Rate (₹/kWh)'] = result['Average Tariff Rate (₹/kWh)'].round(2)
    result['Estimated Monthly Bill (₹)'] = result['Estimated Monthly Bill (₹)'].round(2)

    print("\n🔹 Improved City-wise Predicted Monthly Electricity Bill:")
    print(tabulate(result, headers='keys', tablefmt='grid', showindex=False))

    # Visualization
    plt.figure(figsize=(10, 5))
    sns.barplot(
        x='City',
        y='Estimated Monthly Bill (₹)',
        data=result,
        hue='City',
        palette='coolwarm',
        legend=False
    )

    plt.title('Improved City-wise Predicted Monthly Electricity Bill')
    plt.xlabel('City')
    plt.ylabel('Estimated Monthly Bill (₹)')
    plt.xticks(rotation=45)
    plt.tight_layout()
    plt.show()

