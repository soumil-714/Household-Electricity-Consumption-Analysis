# Total monthly hours per company with split visualization
def total_monthly_hours_per_company():
    total_hours = df.groupby(['Company', 'Months'])['MonthlyHours'].sum().unstack()
    print("\nTotal Monthly Hours per Company:")
    print(tabulate(total_hours, headers='keys', tablefmt='grid'))

    companies = total_hours.index
    num_companies = len(companies)

    # Dynamically determine grid size
    rows = (num_companies // 2) + (num_companies % 2)
    cols = min(2, num_companies)

    fig, axes = plt.subplots(rows, cols, figsize=(12, 5 * rows))
    axes = axes.flatten() if num_companies > 1 else [axes]

    for i, company in enumerate(companies):
        total_hours.loc[company].plot(kind='line', marker='s', ax=axes[i])
        axes[i].set_title(f'Total Monthly Usage Hours: {company}')
        axes[i].set_xlabel('Month')
        axes[i].set_ylabel('Total Usage Hours')

    # Hide any unused subplots
    for j in range(i + 1, len(axes)):
        fig.delaxes(axes[j])

    plt.tight_layout()
    plt.show()

